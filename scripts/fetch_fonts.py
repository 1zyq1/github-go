"""Download the self-hosted woff2 assets and generate the @font-face stylesheet.

Usage:
    uv run --no-project python scripts/fetch_fonts.py <repository-root>

The script is idempotent: already downloaded files are reused, so the
generated stylesheet can be rebuilt without re-fetching megabytes of fonts.
"""

import logging
import pathlib
import re
import sys
import urllib.parse
import urllib.request

logger = logging.getLogger("fetch_fonts")

USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)
ALLOWED_HOSTS = frozenset({"fonts.googleapis.com", "fonts.gstatic.com"})
_FONT_FACE = re.compile(r"@font-face\s*\{(.*?)\}", re.DOTALL)
_WOFF2_URL = re.compile(r"url\((https://[^)]+\.woff2)\)")
_FAMILY_SOURCES: dict[str, tuple[str, str]] = {
    "Plus Jakarta Sans": (
        "https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@200..800&display=swap",
        "jakarta",
    ),
    "Noto Sans SC": (
        "https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@100..900&display=swap",
        "noto-sc",
    ),
}


class UnexpectedSourceError(ValueError):
    """Raised when a font URL points somewhere other than the font CDNs."""

    def __init__(self, url: str) -> None:
        """Record the rejected URL in the error message."""
        super().__init__(f"refusing to fetch from unexpected source: {url}")


def fetch(url: str) -> bytes:
    """Download one https URL, rejecting any host outside the font CDNs."""
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.netloc not in ALLOWED_HOSTS:
        raise UnexpectedSourceError(url)
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})  # noqa: S310
    with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
        return bytes(response.read())


def declaration(block: str, name: str) -> str:
    """Read one CSS declaration value out of an @font-face block."""
    match = re.search(rf"{name}:\s*([^;]+);", block)
    return match.group(1).strip() if match else ""


def face_rule(family: str, block: str, slug: str, label: str) -> str:
    """Render one @font-face rule that points at the local woff2 file."""
    lines = [
        "@font-face {",
        f'  font-family: "{family}";',
        f"  font-style: {declaration(block, 'font-style') or 'normal'};",
        f"  font-weight: {declaration(block, 'font-weight') or '400'};",
    ]
    stretch = declaration(block, "font-stretch")
    if stretch:
        lines.append(f"  font-stretch: {stretch};")
    lines.append("  font-display: swap;")
    lines.append(f'  src: url("/fonts/{slug}/{label}") format("woff2");')
    unicode_range = declaration(block, "unicode-range")
    if unicode_range:
        lines.append(f"  unicode-range: {unicode_range};")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    """Refresh every family and write the generated stylesheet."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = pathlib.Path(sys.argv[1])
    fonts_dir = root / "frontend" / "public" / "fonts"
    fonts_dir.mkdir(parents=True, exist_ok=True)
    rules: list[str] = []
    downloaded = 0
    for family, (stylesheet_url, slug) in _FAMILY_SOURCES.items():
        css = fetch(stylesheet_url).decode("utf-8")
        kept = 0
        for block in _FONT_FACE.findall(css):
            match = _WOFF2_URL.search(block)
            if match is None:
                continue
            remote = match.group(1)
            label = remote.rsplit("/", 1)[-1]
            target = fonts_dir / slug / label
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists():
                _ = target.write_bytes(fetch(remote))
                downloaded += target.stat().st_size
            rules.append(face_rule(family, block, slug, label))
            kept += 1
        logger.info("%s: %d faces", family, kept)
    stylesheet = root / "frontend" / "src" / "styles" / "fonts.css"
    stylesheet.parent.mkdir(parents=True, exist_ok=True)
    _ = stylesheet.write_text(
        "/* Generated by scripts/fetch_fonts.py. Do not edit by hand. */\n"
        + "\n".join(rules)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    logger.info("downloaded %.2f MiB", downloaded / 1024 / 1024)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
